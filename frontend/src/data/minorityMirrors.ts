export function getMinorityMirror(
  slug: string,
  optionId: string,
): MinorityMirror | null {
  return minorityMirrors[slug]?.[optionId] ?? null
}

// Заголовок хранится с плейсхолдером {percent} — реальный процент (тот же,
// что показан на экране результата) подставляется здесь, а не хранится
// захардкоженным числом, которое могло разойтись с настоящей статистикой.
export function formatMirrorHeadline(
  mirror: MinorityMirror,
  percent: number,
): string {
  return mirror.headline.replace('{percent}', String(percent))
}