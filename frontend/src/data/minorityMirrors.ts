/**
 * «Зеркало меньшинства» — качественный срез для тех, кто выбрал непопулярный вариант.
 *
 * Ключ — slug дилеммы. Значение — словарь: option_id → зеркало.
 * Если пользователь выбрал вариант, для которого зеркала нет — блок не показывается.
 */

export interface MinorityMirror {
  // Порог: показывать зеркало только если процент выбора ≤ этого значения
  maxPercent: number
  // Вступительная фраза — подчёркивает уникальность
  headline: string
  // Три качественных среза — «в каких ситуациях люди с таким же складом мысли принимали похожие решения»
  reflections: string[]
}

