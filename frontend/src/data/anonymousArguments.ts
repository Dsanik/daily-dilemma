/**
 * Возвращает до 3 аргументов от «противников» — тех, кто выбрал НЕ твой вариант.
 */
export function getOpponentArguments(
  slug: string,
  yourOption: string,
  seed: number = Date.now(),
): string[] {
  const allForDilemma = anonymousArguments[slug]
  if (!allForDilemma) return []

  // Собираем аргументы всех вариантов, кроме твоего
  const pool: string[] = []
  for (const [optionId, args] of Object.entries(allForDilemma)) {
    if (optionId !== yourOption) {
      pool.push(...args)
    }
  }

  if (pool.length === 0) return []

  // Простая детерминированная выборка по seed — чтобы не было «перемешивания» при каждом рендере
  const shuffled = [...pool].sort((a, b) => {
    const ha = hashString(a + seed)
    const hb = hashString(b + seed)
    return ha - hb
  })

  return shuffled.slice(0, 3)
}

function hashString(s: string): number {
  let h = 0
  for (let i = 0; i < s.length; i++) {
    h = (h << 5) - h + s.charCodeAt(i)
    h |= 0
  }
  return Math.abs(h)
}